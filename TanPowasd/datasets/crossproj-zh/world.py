def events():
    """展开成事件列表，每个事件一个 id。"""
    out = []
    for key, proj, noun, q, vals in SLOTS:
        for vi, (v, hint, s) in enumerate(vals):
            out.append(dict(id=f"{key}#{vi}", key=key, proj=proj, noun=noun, value=v,
                            prev=vals[vi - 1][0] if vi else None, hint=hint, sess=s,
                            is_update=vi > 0, n_versions=len(vals)))
    return out


def check():
    ev = events()
    ids = {e["id"] for e in ev}
    for q, a, evd in CROSS + DISAMBIG:
        for x in evd:
            assert x in ids, x
    by_s = {}
    for e in ev:
        assert 0 <= e["sess"] < N_SESS
        by_s.setdefault(e["sess"], []).append(e)
    # 更新必须在前一版本之后
    for key, proj, noun, q, vals in SLOTS:
        ss = [s for _, _, s in vals]
        assert ss == sorted(ss), key
    return ev, by_s


